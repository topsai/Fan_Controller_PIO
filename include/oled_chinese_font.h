constexpr size_t C3_CHINESE_GLYPH_COUNT = sizeof(C3_CHINESE_GLYPHS) / sizeof(C3_CHINESE_GLYPHS[0]);

inline const C3ChineseGlyph *c3FindChineseGlyph(const char *utf8Char) {
  if (utf8Char == nullptr || *utf8Char == '\0') {
    return nullptr;
  }
  const uint8_t len = c3Utf8CharLength((uint8_t)*utf8Char);
  for (size_t i = 0; i < C3_CHINESE_GLYPH_COUNT; i++) {
    const char *glyphText = C3_CHINESE_GLYPHS[i].utf8;
    if (strncmp(glyphText, utf8Char, len) == 0 && glyphText[len] == '\0') {
      return &C3_CHINESE_GLYPHS[i];
    }
  }
  return nullptr;
}
